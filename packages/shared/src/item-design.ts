import { z } from 'zod';
export const STANDARD_ITEM_VERSION = 'f0p8b-14.1-1' as const;
export const STANDARD_LAB_VERSION = 'f0p8b-14.1-lab-1' as const;
export const ItemCapabilitySchema = z.enum([
  'direct',
  'configuration',
  'extend_effect',
  'new_mechanic',
  'needs_specification',
]);
const ratio = z.number().int().min(0).max(10000),
  amount = z.number().int().min(0).max(1000000),
  ticks = z.number().int().min(1).max(450);
/** Design-time operations only. P8C must bind each operation to tested core execution. */
export const PlannedItemOperationSchema = z.discriminatedUnion('kind', [
  z.strictObject({
    kind: z.literal('damage_amp'),
    ratioMilli: ratio,
    targetMaxHpAbove: amount.optional(),
  }),
  z.strictObject({ kind: z.literal('ability_critical'), alreadyCriticalBonusMilli: ratio }),
  z.strictObject({
    kind: z.literal('shield'),
    maxHpRatioMilli: ratio,
    healthThresholdMilli: ratio.optional(),
    oncePerCombat: z.boolean(),
  }),
  z.strictObject({ kind: z.literal('resists'), armor: amount, magicResist: amount }),
  z.strictObject({
    kind: z.literal('heal'),
    basis: z.enum(['max_hp', 'missing_hp']),
    ratioMilli: ratio,
    cap: amount.nullable(),
    radius: amount.optional(),
  }),
  z.strictObject({
    kind: z.literal('damage_reduction'),
    ratioMilli: ratio,
    damageClass: z.enum(['all', 'attacks', 'area']),
    healthAboveMilli: ratio.optional(),
    aboveThresholdRatioMilli: ratio.optional(),
  }),
  z.strictObject({
    kind: z.literal('random_items'),
    count: z.literal(2),
    slotCost: z.literal(3),
    pool: z.enum(['requires-specification', 'available-completed-excluding-random']),
  }),
  z.strictObject({
    kind: z.literal('attack_speed_stacks'),
    perStackMilli: ratio,
    stackCap: amount.nullable(),
  }),
  z.strictObject({
    kind: z.literal('resistance_reduction'),
    stat: z.enum(['armor', 'magicResist']),
    ratioMilli: ratio,
    radius: z.number().int().min(0).max(14).optional(),
  }),
  z.strictObject({
    kind: z.literal('cast_punishment'),
    targetMaxManaRatioMilli: ratio,
    radius: amount,
    damageType: z.literal('magic'),
  }),
  z.strictObject({
    kind: z.literal('health_ad_surge'),
    healthThresholdMilli: ratio,
    maxHpRatioMilli: ratio,
    adRatioMilli: ratio,
    oncePerCombat: z.literal(true),
  }),
  z.strictObject({
    kind: z.literal('targeting_resists'),
    armorPerEnemy: amount,
    magicResistPerEnemy: amount,
  }),
  z.strictObject({
    kind: z.literal('retaliation'),
    damage: amount,
    damageType: z.literal('magic'),
    radius: z.literal(1),
  }),
  z.strictObject({
    kind: z.literal('burn_wound'),
    burnPerSecondMilli: ratio,
    tickIntervalTicks: z.literal(10),
    woundMilli: ratio,
    damageType: z.literal('true'),
    radius: z.number().int().min(0).max(14).optional(),
  }),
  z.strictObject({
    kind: z.literal('omnivamp'),
    ratioMilli: ratio,
    alsoHealLowestHpAlly: z.boolean(),
  }),
  z.strictObject({
    kind: z.literal('round_random_bonus'),
    adMilli: ratio,
    ap: amount,
    omnivampMilli: ratio,
    weights: z.enum(['requires-specification', 'eunuco-even']),
  }),
  z.strictObject({
    kind: z.literal('untargetable_cleanse'),
    healthThresholdMilli: ratio,
    untargetableTicks: ticks,
    oncePerCombat: z.literal(true),
  }),
  z.strictObject({ kind: z.literal('attack_speed'), ratioMilli: ratio }),
  z.strictObject({
    kind: z.literal('dual_power_stacks'),
    adPerStackMilli: ratio,
    apPerStack: amount,
    stackCap: amount,
    armorAtCap: amount,
    magicResistAtCap: amount,
  }),
  z.strictObject({
    kind: z.literal('secondary_bolt'),
    adRatioMilli: ratio,
    additionalTargets: z.number().int().min(1).max(8),
    damageType: z.literal('physical'),
    sourceProcs: z.enum(['disabled-pending-validation', 'physical-shred-and-omnivamp']),
  }),
  z.strictObject({ kind: z.literal('ability_power'), amount }),
  z.strictObject({ kind: z.literal('attack_mana'), amount }),
  z.strictObject({
    kind: z.literal('positional_bonuses'),
    frontRows: z.literal(2),
    frontArmor: amount,
    frontMagicResist: amount,
    frontManaPerAttackReceived: amount,
    backAp: amount,
    backMana: amount,
    backIntervalTicks: ticks,
  }),
  z.strictObject({
    kind: z.literal('max_mana_reduction'),
    amount,
    minimumMana: z.union([z.literal('requires-specification'), z.number().int().min(1)]),
  }),
  z.strictObject({ kind: z.literal('crowd_control_immunity') }),
  z.strictObject({
    kind: z.literal('chain_magic'),
    everyAttacks: z.literal(3),
    damage: amount,
    targets: z.number().int().min(1).max(56),
    shredMilli: ratio,
  }),
]);
export type PlannedItemOperation = z.infer<typeof PlannedItemOperationSchema>;
export const PlannedItemEffectSchema = z.strictObject({
  id: z.string().min(1).max(80),
  implementation: z.enum(['reserved-design-v2', 'executable-v1']),
  trigger: z.enum([
    'combat_start',
    'attack_release',
    'attack_hit',
    'received_attack',
    'aura',
    'damage_taken',
    'damage_dealt',
    'physical_damage',
    'shield_damage',
    'enemy_cast',
    'ability_cast',
    'periodic',
    'health_threshold',
    'shield_expire',
    'targeting_change',
    'round_start',
    'attack_or_damage_taken',
    'attack_or_ability_damage',
    'takedown',
  ]),
  target: z.enum([
    'self',
    'current_enemy',
    'enemies_in_radius',
    'allies_in_radius',
    'nearby_enemy',
    'lowest_hp_ally_and_self',
    'damaged_enemy',
    'casting_enemy',
  ]),
  operation: PlannedItemOperationSchema,
  condition: z
    .strictObject({
      healthAtOrBelowMilli: ratio.optional(),
      afterEffectId: z.string().optional(),
      duringFirstTicks: ticks.optional(),
      oncePerCombat: z.boolean().optional(),
    })
    .optional(),
  durationTicks: ticks.nullable(),
  intervalTicks: ticks.optional(),
  cooldownTicks: ticks.optional(),
  stacking: z.enum(['add', 'independent', 'refresh', 'strongest', 'unique', 'nonstacking_debuff']),
  capability: ItemCapabilitySchema,
  note: z.string().max(1000),
});
export type PlannedItemEffect = z.infer<typeof PlannedItemEffectSchema>;
export const ItemContentSchema = z.strictObject({
  definition: z.literal('complete'),
  combat: z.enum(['compatible', 'pending']),
  laboratory: z.boolean(),
  competitive: z.boolean(),
  internalName: z.string().min(1).max(80),
  accessibleLabel: z.string().min(1).max(160),
  visibleName: z.null(),
  functionalCategory: z.enum([
    'component',
    'physical',
    'magic',
    'defense',
    'support',
    'hybrid',
    'utility',
  ]),
  slotCost: z.union([z.literal(1), z.literal(3)]),
  sourceRecordId: z.string().min(1).max(100),
  usedParameters: z.array(z.string()),
  uninterpretedParameters: z.array(z.string()),
});
